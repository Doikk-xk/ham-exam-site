def load_b():
    s = open(EXAM_JS, encoding="utf-8").read()
    m = re.search(r"window.__EXAM_DATA__ = (\{.*\})\s*;?\s*$", s, re.S)
    d = json.loads(m.group(1))
    qs = d["b"]["q"]
    return {q["c"]: q for q in qs}


def load_a_only():
    """载入 A 类中 code 不在 B 类的独有题（这些题解析不会因共享 code 而自动复用）。"""
    s = open(EXAM_JS, encoding="utf-8").read()
    m = re.search(r"window.__EXAM_DATA__ = (\{.*\})\s*;?\s*$", s, re.S)
    d = json.loads(m.group(1))
    bcodes = {q["c"] for q in d["b"]["q"]}
    out = {}
    for q in d["a"]["q"]:
        if q["c"] not in bcodes:
            out[q["c"]] = q
    return out


